package com.kannan.webhook_platform.controller;

import io.swagger.v3.oas.annotations.Operation;
import io.swagger.v3.oas.annotations.tags.Tag;
import com.kannan.webhook_platform.dto.EventRequest;
import com.kannan.webhook_platform.dto.EventResponse;
import com.kannan.webhook_platform.entity.Event;
import com.kannan.webhook_platform.service.EventService;
import jakarta.validation.Valid;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.*;
import com.kannan.webhook_platform.dto.DeliveryAttemptResponse;
import java.util.List;
import java.util.UUID;

@RestController
@RequestMapping("/events")
@Tag(name = "Endpoints", description = "Register and manage webhook destination URLs")
public class EventController {

    private final EventService eventService;

    public EventController(EventService eventService) {
        this.eventService = eventService;
    }

    @Operation(summary = "Register a new webhook endpoint", description = "The signing secret is generated by the server and never returned in responses.")
    @PostMapping
    public ResponseEntity<EventResponse> create(@Valid  @RequestBody EventRequest request) {
        Event created = eventService.ingestEvent(
                request.getTenantId(), request.getEventType(), request.getPayload());
        return ResponseEntity.ok(EventResponse.fromEntity(created));
    }
    @Operation(summary = "Get the full delivery attempt history for an event")
    @GetMapping("/{id}/deliveries")
    public ResponseEntity<List<DeliveryAttemptResponse>> getDeliveries(@PathVariable UUID id) {
        List<DeliveryAttemptResponse> history = eventService.getDeliveryHistory(id)
                .stream().map(DeliveryAttemptResponse::fromEntity).toList();
        return ResponseEntity.ok(history);
    }
}