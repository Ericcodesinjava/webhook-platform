package com.kannan.webhook_platform.controller;

import io.swagger.v3.oas.annotations.Operation;
import io.swagger.v3.oas.annotations.tags.Tag;
import com.kannan.webhook_platform.dto.EndpointRequest;
import com.kannan.webhook_platform.dto.EndpointResponse;
import com.kannan.webhook_platform.entity.Endpoint;
import com.kannan.webhook_platform.service.EndpointService;
import jakarta.validation.Valid;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.*;

import java.util.List;
import java.util.UUID;

@RestController
@RequestMapping("/endpoints")
@Tag(name = "Endpoints", description = "Register and manage webhook destination URLs")
public class EndpointController {

    private final EndpointService endpointService;

    public EndpointController(EndpointService endpointService) {
        this.endpointService = endpointService;
    }

    @Operation(summary = "Register a new webhook endpoint", description = "The signing secret is generated by the server and never returned in responses.")
    @PostMapping
    public ResponseEntity<EndpointResponse> create(@Valid @RequestBody EndpointRequest request) {
        Endpoint created = endpointService.createEndpoint(
                request.getTenantId(), request.getUrl(), request.getSubscribedEventTypes());
        return ResponseEntity.ok(EndpointResponse.fromEntity(created));
    }

    @GetMapping
    public ResponseEntity<List<EndpointResponse>> list(@RequestParam String tenantId) {
        List<EndpointResponse> responses = endpointService.getEndpointsForTenant(tenantId)
                .stream().map(EndpointResponse::fromEntity).toList();
        return ResponseEntity.ok(responses);
    }

    @PatchMapping("/{id}")
    public ResponseEntity<EndpointResponse> update(@PathVariable UUID id, @RequestBody EndpointRequest request) {
        Endpoint updated = endpointService.updateEndpoint(id, request.getUrl(), request.getSubscribedEventTypes());
        return ResponseEntity.ok(EndpointResponse.fromEntity(updated));
    }

    @DeleteMapping("/{id}")
    public ResponseEntity<Void> delete(@PathVariable UUID id) {
        endpointService.deleteEndpoint(id);
        return ResponseEntity.noContent().build();
    }
}